# Generates devwrap.h: a forwarding COM wrapper for IDirect3DDevice9 from the SDK header.
import re, sys
hdr = open(sys.argv[1], encoding='latin-1').read()
start = hdr.index('DECLARE_INTERFACE_(IDirect3DDevice9, IUnknown)')
body = hdr[start:hdr.index('};', start)]
body = re.sub(r'\s+', ' ', body)
meths = re.findall(r'STDMETHOD(?:_\(\s*([\w\s\*]+?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS_?\s*(.*?)\)\s*PURE\s*;', body)
custom = set(sys.argv[2].split(','))
out = ['// Generated by gen_wrap.py from d3d9.h - do not edit.', '']
names = []
for ret, n1, n2, params in meths:
    name = n1 or n2
    ret = ret.strip() if n1 else 'HRESULT'
    names.append(name)
    params = params.strip()
    plist = [p.strip() for p in params.split(',')] if params else []
    args = []
    for i, p in enumerate(plist):
        m = re.search(r'(\w+)\s*(\[\s*\w*\s*\])?$', p)
        toks = re.sub(r'CONST|const', '', p).split()
        if not m or len(toks) < 2 or p.rstrip().endswith('*'):   # unnamed, e.g. "CONST D3DMATRIX*"
            plist[i] = p + ' a%d' % i
            args.append('a%d' % i)
        else:
            args.append(m.group(1))
    if name in custom:
        continue
    decl = ', '.join(['IDirect3DDevice9 *This'] + plist)
    call = ', '.join(['R(This)'] + args)
    ret_kw = '' if ret == 'void' else 'return '
    out.append('static %s WINAPI W_%s(%s) { %sR(This)->lpVtbl->%s(%s); }' % (ret, name, decl, ret_kw, name, call))
out.append('')
out.append('static IDirect3DDevice9Vtbl g_wrapVtbl = {')
for n in names:
    out.append('    W_%s,' % n)
out.append('};')
open('devwrap.h', 'w').write('\n'.join(out) + '\n')
print(len(names), 'methods,', len(names) - len(custom & set(names)), 'generated')
